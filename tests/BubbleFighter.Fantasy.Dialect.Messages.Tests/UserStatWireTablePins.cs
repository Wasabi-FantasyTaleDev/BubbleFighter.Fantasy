using BubbleFighter.Fantasy.Packets;
using Xunit;

namespace BubbleFighter.Fantasy.Dialect.Messages.Tests;

/// <summary>
/// Pins S2C <c>gspUserStat</c> (105) after the writer stopped selecting the modern FighterInfo values by the
/// <c>family: modern</c> value and started following the build's own <c>FighterInfo</c> table: <c>unknown_504</c>
/// in that table is the statement that the block carries the identity at +4, the character type at +32 and the
/// display name at +504 (reader kr-1256 sub_115A6D0, gspUserStat reader kr-1256 sub_9D8030). The modern family
/// keeps the bytes the pre-move writer produced (the <c>Golden/modern-lobby.txt</c> entries) and the legacy kr-812
/// body keeps its named pin (kr-812 sub_81A820 counters, kr-812 sub_87DD90 name and level).
/// </summary>
public sealed class UserStatWireTablePins
{
    private static readonly PacketTables Tables = PacketTables.Load(TestBuilds.PacketsDirectory());

    /// <summary>The golden modern sample: color 3, lucci 1234, cash 5678, identity 1001, nickname "nick", level 10.</summary>
    [Fact]
    public void Kr1256BodyIsUnchanged()
    {
        Pin("kr-1256", "nick", 10, 1234, 5678, 3, 1001, 494, Kr1256Body);
    }

    /// <summary>cn-774 states one more word after the u16 and a 23-byte larger FighterInfo, so its body is 521.</summary>
    [Fact]
    public void Cn774BodyIsUnchanged()
    {
        Pin("cn-774", "nick", 10, 1234, 5678, 3, 1001, 521, Cn774Body);
    }

    /// <summary>tw-454 follows cn-774's UserStat and FighterInfo tables; its body is the same 521 bytes.</summary>
    [Fact]
    public void Tw454BodyIsUnchanged()
    {
        Pin("tw-454", "nick", 10, 1234, 5678, 3, 1001, 513, Tw454Body);
    }

    /// <summary>The legacy named pin: color 0, lucci 7, cash 9, nickname "ab", level 5, 384 bytes.</summary>
    [Fact]
    public void LegacyKr812NamedBodyIsUnchanged()
    {
        Pin("kr-812", "ab", 5, 7, 9, 0, 0, 384, Kr812Body);
    }

    /// <summary>
    /// The modern values are chosen by the table, and the table says so for exactly the modern family: the builds
    /// whose FighterInfo has an <c>unknown_504</c> row are kr-1256 and the two builds based on it, so no legacy
    /// build's bytes change. A build added later states the same row to join the family.
    /// </summary>
    [Fact]
    public void TheModernValuesFollowTheBuildsFighterInfoTable()
    {
        var modern = Tables.Builds
            .Where(build => Tables.Resolve(build, "FighterInfo").Any(field => field.Name == "unknown_504"))
            .ToArray();
        Assert.Equal(["kr-1256", "cn-774", "tw-454"], modern);
        Assert.DoesNotContain(Tables.Resolve("kr-812", "FighterInfo"), field => field.Name == "unknown_504");
    }

    private static void Pin(string build, string nickname, int level, int lucci, int cash, ushort colorIndex,
        long userNum, int length, string hex)
    {
        var body = UserStatWire.Write(Tables, build, nickname, level, lucci, cash, colorIndex, userNum);
        Assert.Equal(length, body.Length);
        Assert.Equal(hex, Convert.ToHexString(body));
    }

    private const string Kr1256Body =
