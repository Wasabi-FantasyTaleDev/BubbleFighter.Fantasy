using BubbleFighter.Fantasy.Contracts.Rooms;
using BubbleFighter.Fantasy.Dialect.Rooms;
using Xunit;

namespace BubbleFighter.Fantasy.Dialect.Messages.Tests;

/// <summary>
/// Pins the room chat line both families sent before their writers were merged: the legacy line carries the
/// channel and lets the client colour channel 1 (kr-812 sub_8023E0), the modern line carries channel 0 and the
/// channel-1 colour word (kr-1256 sub_9DE360). One writer now produces both from builds.yaml room_chat_colour.
/// </summary>
public sealed class RoomChatSharedWireTests
{
    [Theory]
    [InlineData("kr-812", 0, "02000100000041000000000000000000010000004200FFFFFFFF0000000000000000")]
    [InlineData("kr-812", 1, "02000100000041000100000000000000010000004200FFFFFFFF0000000000000000")]
    [InlineData("cn-324", 0, "02000100000041000000000000000000010000004200FFFFFFFF00000000")]
    [InlineData("cn-324", 1, "02000100000041000100000000000000010000004200FFFFFFFF00000000")]
    [InlineData("id-400", 0, "02000100000041000000000000000000010000004200FFFFFFFF00000000")]
    [InlineData("id-400", 1, "02000100000041000100000000000000010000004200FFFFFFFF00000000")]
    [InlineData("id-1809", 0, "02000100000041000000000000000000010000004200FFFFFFFF0000000000000000")]
    [InlineData("id-1809", 1, "02000100000041000100000000000000010000004200FFFFFFFF0000000000000000")]
    [InlineData("cn-406", 0, "02000100000041000000000000000000010000004200FFFFFFFF00000000")]
    [InlineData("cn-406", 1, "02000100000041000100000000000000010000004200FFFFFFFF00000000")]
    [InlineData("cn-706", 0, "02000100000041000000000000000000010000004200FFFFFFFF0000000000000000")]
    [InlineData("cn-706", 1, "02000100000041000100000000000000010000004200FFFFFFFF0000000000000000")]
    [InlineData("kr-1256", 0, "0200010000004100000000000000000000000000010000004200FFFFFFFF00000000000000000000000000000000")]
    [InlineData("kr-1256", 1, "0200010000004100000000000000000000000000010000004200A1A1FFFF00000000000000000000000000000000")]
    [InlineData("cn-774", 0, "0200010000004100000000000000000000000000010000004200FFFFFFFF00000000000000000000000000000000")]
    [InlineData("cn-774", 1, "0200010000004100000000000000000000000000010000004200A1A1FFFF00000000000000000000000000000000")]
    [InlineData("tw-454", 0, "0200010000004100000000000000000000000000010000004200FFFFFFFF000000000000000000000000")]
    [InlineData("tw-454", 1, "0200010000004100000000000000000000000000010000004200A1A1FFFF000000000000000000000000")]
    public void OneWriterKeepsEveryBuildsChatBytes(string build, int channel, string hex) =>
        Assert.Equal(hex, Convert.ToHexString(RoomChatBinding.Write(TestBuilds.Packets, build, new RoomChatReceived(7, 2, "A", channel, "B"))));
}
