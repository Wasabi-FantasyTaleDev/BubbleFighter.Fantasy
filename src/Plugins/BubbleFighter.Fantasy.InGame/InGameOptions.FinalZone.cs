using System.ComponentModel.DataAnnotations;

namespace BubbleFighter.Fantasy.InGame;

public sealed partial class InGameOptions
{
    /// <summary>Gets or sets the maximum simultaneously active drones in one FinalZone room.</summary>
    [Range(1, 1000)]
    public int FinalZoneMaximumDrones { get; set; } = 1;

    /// <summary>Gets or sets the maximum distinct golden-supply requests accepted from the map-script master per round.</summary>
    [Range(0, 1000)]
    public int FinalZoneMaximumGoldenSupplies { get; set; } = 3;

    /// <summary>Gets or sets the first scene handle reserved for FinalZone items and backpacks.</summary>
    [Range(1, int.MaxValue)]
    public int FinalZoneFirstObjectId { get; set; } = 65536;

    /// <summary>Gets or sets the total nonreusable item and backpack handles available in one FinalZone round.</summary>
    [Range(1, 1000000)]
    public int FinalZoneMaximumObjects { get; set; } = 16384;

    /// <summary>Gets or sets the largest native item amount accepted or retained per specification.</summary>
    [Range(1, int.MaxValue)]
    public int FinalZoneMaximumQuantity { get; set; } = 100000;

    /// <summary>Gets or sets the size limit for each imported FinalZone map or item resource.</summary>
    [Range(1, int.MaxValue)]
    public int FinalZoneMaximumFileBytes { get; set; } = 4194304;

    /// <summary>Gets or sets the row limit for each native FinalZone spawn table.</summary>
    [Range(1, 1000000)]
    public int FinalZoneMaximumRows { get; set; } = 16384;

    /// <summary>Gets or sets the maximum generated-item specifications accepted from client data.</summary>
    [Range(1, 100000)]
    public int FinalZoneMaximumItemSpecs { get; set; } = 4096;

    /// <summary>Gets or sets the maximum alternatives accepted in one native spawn candidate field.</summary>
    [Range(1, 10000)]
    public int FinalZoneMaximumAlternatives { get; set; } = 256;

    /// <summary>Gets or sets the maximum accompanying objects generated by one native spawn choice.</summary>
    [Range(0, 10000)]
    public int FinalZoneMaximumBonusItems { get; set; } = 64;
}
