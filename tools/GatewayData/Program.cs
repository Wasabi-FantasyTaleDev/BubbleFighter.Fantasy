using System.Globalization;
using System.Collections;
using System.Text;
using System.Text.Json;
using BubbleFighter.Fantasy.Abstractions.Protocol;
using BubbleFighter.Fantasy.Kernel;
using BubbleFighter.Fantasy.Packets;
using BubbleFighter.Fantasy.Protocol;

if (args is ["--smoke", var repository, var executable])
{
    await NativeSmoke.RunAsync(repository, executable);
    return;
}
if (args is ["--smoke-automatic", var automaticRepository, var automaticExecutable])
{
    await NativeAutomaticSmoke.RunAsync(automaticRepository, automaticExecutable);
    return;
}

if (args is not [var root, var destination])
    throw new ArgumentException("Expected repository root and generated C# output path.");

var tables = PacketTables.Load(Path.Combine(root, "packets"));
var composer = new ProfileComposer(Path.Combine(root, "profiles"), _ => null, unsetReadsEmpty: true);
using var manifest = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "src/FantasyTale.Gateway/profiles/bf-center-selector.json")));
var builds = manifest.RootElement.GetProperty("builds").EnumerateArray().Select(item => item.GetString()!).ToArray();
var bootstrapBuilds = manifest.RootElement.GetProperty("bootstrap_exchange_builds").EnumerateObject()
    .ToDictionary(item => item.Name, item => item.Value, StringComparer.Ordinal);
var observationBuilds = manifest.RootElement.GetProperty("bootstrap_observation_builds").EnumerateObject()
    .ToDictionary(item => item.Name, item => item.Value, StringComparer.Ordinal);
if (bootstrapBuilds.Keys.Except(builds, StringComparer.Ordinal).Any())
    throw new InvalidOperationException("Bootstrap exchanges require a supported build.");
if (observationBuilds.Keys.Except(builds, StringComparer.Ordinal).Any())
    throw new InvalidOperationException("Bootstrap observations require a supported build.");
var identityBuilds = manifest.RootElement.GetProperty("selector_identity_builds").EnumerateArray().Select(item => item.GetString()!).ToArray();
var automaticBuilds = manifest.RootElement.GetProperty("automatic_center_builds").EnumerateObject()
    .ToDictionary(item => item.Name, item => item.Value.GetString()!, StringComparer.Ordinal);
var releaseBuilds = manifest.RootElement.GetProperty("handoff_release_builds").EnumerateObject()
    .ToDictionary(item => item.Name, item => item.Value, StringComparer.Ordinal);
if (releaseBuilds.Keys.Except(automaticBuilds.Keys, StringComparer.Ordinal).Any())
    throw new InvalidOperationException("Native source release requires an automatic Center adapter.");
if (automaticBuilds.Keys.Except(builds, StringComparer.Ordinal).Any() || automaticBuilds.Values.Any(string.IsNullOrWhiteSpace))
    throw new InvalidOperationException("Automatic Center adapters must be unique supported builds.");
if (identityBuilds.Distinct(StringComparer.Ordinal).Count() != identityBuilds.Length || identityBuilds.Except(builds, StringComparer.Ordinal).Any())
    throw new InvalidOperationException("Selector identity adapters must be unique supported builds.");
if (builds.Distinct(StringComparer.Ordinal).Count() != builds.Length)
    throw new InvalidOperationException("Gateway build manifest contains duplicate identities.");
var source = new StringBuilder("// <auto-generated/>\nnamespace FantasyTale.Gateway;\n\ninternal static class CompiledBuildCatalog\n{\n    internal static BubbleFighterBuildProfile Resolve(string id) => id switch\n    {\n");
foreach (var id in builds)
{
    // Offline composition must not bake a developer's overrides or deployment credentials into the product.
    if (Directory.EnumerateFiles(Path.Combine(root, "profiles"), "*local.patch.yaml", SearchOption.AllDirectories).Any())
        throw new InvalidOperationException("Generate Gateway data from a checkout without local profile overrides.");
    var rows = composer.Compose(id, []);
    var dialect = rows.Single(row => row.Id == "dialect");
    var protocol = rows.Single(row => row.Id == "protocol");
    var build = dialect.ClientBuild ?? throw new InvalidOperationException($"Missing build identity: {id}.");
    var profile = new ClientProfile(id, build.Region, build.Major, 0, build.Resource, id);
    var opcodes = OpcodeTableLoader.Load(Path.Combine(root, "profiles", id, "opcodes.yaml"), profile);
    var patchRequestName = protocol.Config?.GetValueOrDefault("patch_request_name")?.ToString() ?? "gcpFirstConnect";
    PacketLayoutContract.RequireFields(tables, id, "gcpFirstConnect", "Gateway bootstrap", ("client_version", "u32"));
    PacketLayoutContract.RequireFields(tables, id, "gspRepGamePatch", "Gateway bootstrap", ("requires_patch", "bool"), ("command_line", "wstr"));
    PacketLayoutContract.RequireFields(tables, id, "gspCenterList", "Gateway directory", ("gates", "list<GateInfo>"));
    var legacyDirectory = tables.Resolve(id, "GateInfo").Any(field => field.Name == "key");
    if (legacyDirectory)
        PacketLayoutContract.RequireFields(tables, id, "GateInfo", "Gateway directory",
            ("key", "u32"), ("sub_key", "u32"), ("unknown_12", "u32"), ("address", "u32"), ("port", "u16"));
    else
        PacketLayoutContract.RequireFields(tables, id, "GateInfo", "Experimental Gateway directory",
            ("unknown_4", "u32"), ("unknown_8", "u32"), ("unknown_12", "u32"), ("unknown_16", "u32"), ("unknown_20", "u16"));
    var values = tables.ValuesOf(id);
    foreach (var key in new[] { "gateway_center_group", "gateway_reserved_center" })
        if (!int.TryParse(values.GetValueOrDefault(key)?.ToString(), CultureInfo.InvariantCulture, out var value) || value is < 0 or > 65500)
            throw new InvalidOperationException($"{id}: {key} must be a non-negative bounded native grouping key.");
    string Config(string key, string fallback = "") => dialect.Config?.GetValueOrDefault(key)?.ToString() ?? fallback;
    var marker = opcodes.All.SingleOrDefault(entry => entry.Direction == PacketDirection.ClientToServer && entry.Name == "gcpStartGPK");
    var keepAlivePing = opcodes.All.SingleOrDefault(entry => entry.Direction == PacketDirection.ClientToServer && entry.Name == "gcpReqKeepAlivePing");
    var preHandshake = protocol.Config?.GetValueOrDefault("pre_handshake_opcodes") is IEnumerable valuesList
        ? valuesList.Cast<object>().Select(value => opcodes.Find(PacketDirection.ClientToServer, value.ToString()!)
            ?? throw new InvalidOperationException($"{id}: pre-handshake packet '{value}' is absent from the client-to-server table.")).ToArray()
        : [];
    if (keepAlivePing is not null && (keepAlivePing.Evidence != Evidence.Verified || tables.Resolve(id, keepAlivePing.Name).Count != 0))
        throw new InvalidOperationException($"{id}: Gateway keep-alive requires a verified opcode and an empty canonical layout.");
    source.AppendLine($"        {Quote(id)} => new({Quote(id)}, {Quote(build.Region)}, {build.Major}, {build.Resource},");
    source.AppendLine($"            {Quote(Config("frame"))}, {Quote(Config("cipher_table_a"))}, {Quote(Config("cipher_table_b"))},");
    var status = Convert.ToUInt16(protocol.Config?.GetValueOrDefault("bootstrap_status")
        ?? throw new InvalidOperationException($"{id}: Gateway requires an explicit canonical bootstrap status."), CultureInfo.InvariantCulture);
    source.AppendLine($"            {status}, {opcodes.C2S(patchRequestName)}, {opcodes.S2C("gspRepGamePatch")}, {opcodes.S2C("gspCenterList")}, {(marker is null ? "null" : marker.Value.ToString(CultureInfo.InvariantCulture))}, {(keepAlivePing is null ? "null" : keepAlivePing.Value.ToString(CultureInfo.InvariantCulture))},");
    source.AppendLine($"            {values["gateway_center_group"]}, {values["gateway_reserved_center"]}, {identityBuilds.Contains(id, StringComparer.Ordinal).ToString().ToLowerInvariant()}, {(!legacyDirectory).ToString().ToLowerInvariant()}, {Quote(protocol.Config?.GetValueOrDefault("bootstrap_command_line")?.ToString() ?? "")}, [{string.Join(", ", preHandshake)}],");
    var automatic = "null";
    if (automaticBuilds.TryGetValue(id, out var promotionName))
    {
        PacketLayoutContract.RequireFields(tables, id, "ChannelMoveOffer", "Gateway native redirect",
            ("result", "u32"), ("ipv4_word", "u32"), ("port", "u16"));
        PacketLayoutContract.RequireSignature(tables, id, "PromotePendingConnection", "Gateway native redirect", "");
        var release = "null";
        if (releaseBuilds.TryGetValue(id, out var releaseConfig))
        {
            PacketLayoutContract.RequireEmpty(tables, id, "PendingPromotionAcknowledgement", "Gateway native source release");
            PacketLayoutContract.RequireEmpty(tables, id, "CompletePendingPromotion", "Gateway native source release");
            release = $"new NativeHandoffRelease({opcodes.C2S(releaseConfig.GetProperty("request").GetString()!)}, "
                + $"{opcodes.S2C(releaseConfig.GetProperty("reply").GetString()!)}, "
                + $"{Layout(id, "PendingPromotionAcknowledgement")}, {Layout(id, "CompletePendingPromotion")})";
        }
        automatic = $"new AutomaticCenterProtocol({opcodes.C2S("gcpReqCenterUserCnt")}, {opcodes.S2C("gspRepCenterUserCnt")}, "
            + $"{opcodes.C2S("gcpReqUniquenessCheck")}, {opcodes.S2C("gspRepUniquenessCheck")}, {opcodes.C2S("gcpReqLogin")}, "
            + $"{opcodes.S2C("gspRepMoveChannel")}, {opcodes.S2C(promotionName)}, "
            + $"{Layout(id, "CenterStatus")}, {Layout(id, "CenterAvailabilityReply")}, {Layout(id, "PreloginRedirectRequest")}, "
            + $"{Layout(id, "ChannelMoveOffer")}, {Layout(id, "PromotePendingConnection")}, {release})";
    }
    var exchanges = new List<string>();
    if (bootstrapBuilds.TryGetValue(id, out var exchangeRows))
    {
        var requests = new HashSet<ushort>();
        if (exchangeRows.GetArrayLength() is < 1 or > 8)
            throw new InvalidOperationException($"{id}: bootstrap exchanges require 1..8 audited entries.");
        foreach (var exchange in exchangeRows.EnumerateArray())
        {
            var requestName = exchange.GetProperty("request").GetString()!;
            var replyName = exchange.GetProperty("reply").GetString()!;
            var request = opcodes.All.Single(entry => entry.Direction == PacketDirection.ClientToServer && entry.Name == requestName);
            var reply = opcodes.All.Single(entry => entry.Direction == PacketDirection.ServerToClient && entry.Name == replyName);
            if (request.Evidence != Evidence.Verified || reply.Evidence != Evidence.Verified || !requests.Add(request.Value)
                || request.Value == opcodes.C2S(patchRequestName) || request.Value == marker?.Value || request.Value == keepAlivePing?.Value)
                throw new InvalidOperationException($"{id}: bootstrap exchange requires distinct verified native opcodes.");
            var replyValues = exchange.GetProperty("reply_values").EnumerateObject()
                .ToDictionary(value => value.Name, value => (object?)value.Value.GetInt64(), StringComparer.Ordinal);
            var payload = PacketCodec.Write(tables, id, exchange.GetProperty("reply_layout").GetString()!, replyValues);
            exchanges.Add($"new NativeBootstrapExchange({request.Value}, {reply.Value}, "
                + $"{Layout(id, exchange.GetProperty("request_layout").GetString()!)}, [{string.Join(", ", payload)}])");
        }
    }
    var observations = new List<string>();
    if (observationBuilds.TryGetValue(id, out var observationRows))
    {
        var seen = new HashSet<ushort>();
        foreach (var observation in observationRows.EnumerateArray())
        {
            var name = observation.GetString()!;
            var opcode = opcodes.ForConnection(OpcodeConnection.Game).All.Single(entry => entry.Direction == PacketDirection.ClientToServer && entry.Name == name);
            if (opcode.Evidence != Evidence.Verified || !seen.Add(opcode.Value)
                || opcode.Value == opcodes.C2S(patchRequestName) || opcode.Value == marker?.Value || opcode.Value == keepAlivePing?.Value
                || bootstrapBuilds.TryGetValue(id, out var configuredExchanges) && configuredExchanges.EnumerateArray()
                    .Any(exchange => opcodes.C2S(exchange.GetProperty("request").GetString()!) == opcode.Value))
                throw new InvalidOperationException($"{id}: bootstrap observation requires a distinct verified native game opcode.");
            observations.Add($"new NativeBootstrapObservation({opcode.Value}, {Layout(id, name)})");
        }
    }
    source.AppendLine($"            {Layout(id, "gcpFirstConnect")},\n            {Layout(id, "gspRepGamePatch")},\n            {Layout(id, "gspCenterList")}, {automatic}, [{string.Join(", ", exchanges)}], [{string.Join(", ", observations)}]),");
}
source.AppendLine("        _ => throw new GatewayConfigurationException(\"This client build has no compiled Gateway selector adapter.\"),\n    };\n}");
Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(destination))!);
var content = source.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
if (!File.Exists(destination) || File.ReadAllText(destination) != content)
    File.WriteAllText(destination, content, new UTF8Encoding(false));
var capabilitiesPath = Path.ChangeExtension(destination, ".capabilities.json");
var capabilities = JsonSerializer.Serialize(new
{
    schema_version = 1,
    product = "Fantasy Tale Gateway",
    bootstrap = builds,
    automatic = builds.Where(automaticBuilds.ContainsKey).ToArray(),
}, new JsonSerializerOptions { WriteIndented = true });
if (!File.Exists(capabilitiesPath) || File.ReadAllText(capabilitiesPath) != capabilities)
    File.WriteAllText(capabilitiesPath, capabilities, new UTF8Encoding(false));

string Layout(string build, string name)
{
    var resolved = tables.Resolve(build, name);
    var fields = resolved.Select((field, index) =>
    {
        var kind = field.Type;
        var child = "null";
        var condition = "";
        if (kind.StartsWith("when<", StringComparison.Ordinal))
        {
            var match = System.Text.RegularExpressions.Regex.Match(kind, @"\Awhen<([a-zA-Z_][a-zA-Z_0-9]*)&0x([0-9a-fA-F]+),u32>\z");
            if (!match.Success || !resolved.Take(index).Any(previous => previous.Name == match.Groups[1].Value
                && previous.Type is "u16" or "u32" && previous.Default == 0))
                throw new InvalidOperationException($"{build}: unsupported conditional Gateway field in {name}.");
            var bits = Convert.ToUInt32(match.Groups[2].Value, 16);
            if (bits == 0) throw new InvalidOperationException("Gateway field conditions require a nonzero bit mask.");
            condition = $", {Quote(match.Groups[1].Value)}, {bits}u";
            kind = "u32";
        }
        if (kind.StartsWith("list<", StringComparison.Ordinal) && kind.EndsWith('>'))
        {
            child = Layout(build, kind[5..^1]);
            kind = "List";
        }
        else
            kind = kind switch { "u32" => "Word", "u16" => "Short", "bool" => "Boolean", "wstr" => "WideString", _ => throw new InvalidOperationException($"Unsupported gateway field type {kind}.") };
        return $"new({Quote(field.Name)}, WireFieldKind.{kind}, {field.Default}L, {child}{condition})";
    });
    return $"new CompiledPacket([{string.Join(", ", fields)}])";
}

static string Quote(string text) => JsonSerializer.Serialize(text);
